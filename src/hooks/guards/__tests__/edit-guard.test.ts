import { describe, it, expect } from 'vitest';
import { editGuard, globToRegExp, parseRegistry } from '../edit-guard.js';
import type { HookEvent } from '../../runtime/types.js';

const ev = (filePaths?: string[]): HookEvent => ({
  agent: 'claude-code',
  event: 'PreToolUse',
  sessionId: 's',
  cwd: '/proj',
  tool: { canonical: 'edit', rawName: 'Edit', input: {}, filePaths },
  raw: {},
});

// REAL registry format, as written by `ctk skill-registry`.
const REGISTRY = `# CTK Skill Registry

_Auto-generated by \`ctk skill-registry\`._

| Name | Source | Description | Path |
|------|--------|-------------|------|
| go-testing | user | Go tests \\| Bubbletea | /home/u/.claude/skills/go-testing/SKILL.md |
| react-ui | project | React components | /proj/.claude/skills/react-ui/SKILL.md |
`;

describe('parseRegistry (real Name|Source|Description|Path format)', () => {
  it('extracts name, source, path; unescapes \\| in description', () => {
    expect(parseRegistry(REGISTRY)).toEqual([
      { name: 'go-testing', source: 'user', description: 'Go tests | Bubbletea', path: '/home/u/.claude/skills/go-testing/SKILL.md' },
      { name: 'react-ui', source: 'project', description: 'React components', path: '/proj/.claude/skills/react-ui/SKILL.md' },
    ]);
  });

  it('empty / "No skills found" registry => []', () => {
    expect(parseRegistry('# CTK Skill Registry\n\nNo skills found.\n')).toEqual([]);
  });
});

describe('globToRegExp', () => {
  it('* does not cross /, ** does', () => {
    expect(globToRegExp('src/*.ts').test('src/a.ts')).toBe(true);
    expect(globToRegExp('src/*.ts').test('src/x/a.ts')).toBe(false);
    expect(globToRegExp('**/*.go').test('a/b/c.go')).toBe(true);
    expect(globToRegExp('**/*_test.go').test('pkg/x_test.go')).toBe(true);
  });
});

describe('editGuard', () => {
  const skills = [
    { name: 'go-testing', globs: ['**/*_test.go'] },
    { name: 'react-ui', globs: ['src/client/**/*.tsx', '**/*.stories.tsx'] },
    { name: 'no-globs', globs: [] },
  ];

  it('hints for each matching skill, with the trigger', () => {
    const r = editGuard(ev(['/proj/src/client/Button.tsx']), { skills });
    expect(r).toEqual({
      kind: 'context',
      text: '[ctk-skill-hint] load react-ui (trigger: src/client/**/*.tsx)\n',
    });
  });

  it('matches relative to cwd', () => {
    expect(editGuard(ev(['/proj/pkg/x_test.go']), { skills }).kind).toBe('context');
  });

  it('no match / no globs / no files => noop', () => {
    expect(editGuard(ev(['/proj/README.md']), { skills })).toEqual({ kind: 'noop' });
    expect(editGuard(ev(undefined), { skills })).toEqual({ kind: 'noop' });
    expect(editGuard(ev(['/proj/a.go']), { skills: [{ name: 'n', globs: [] }] })).toEqual({ kind: 'noop' });
  });
});
