import { describe, it, expect } from 'vitest';
import { bashGuard } from '../bash-guard.js';
import type { HookEvent } from '../../runtime/types.js';

const ev = (command?: string): HookEvent => ({
  agent: 'claude-code',
  event: 'PreToolUse',
  sessionId: 's',
  cwd: '/x',
  tool: { canonical: 'shell', rawName: 'Bash', input: {}, command },
  raw: {},
});

describe('bashGuard', () => {
  it.each([
    ['git commit -m "feat: x\n\nCo-Authored-By: Claude <a@b.c>"', 'Co-Authored-By'],
    ['git commit -m "x" -m "co-authored-by: bot"', 'Co-Authored-By'],
    ['git commit -m "Generated with [Claude Code]"', 'Generated with'],
    ['git commit -m "🤖 Generated by tool"', '🤖 Generated'],
    ['git commit -m "x <noreply@anthropic.com>"', 'noreply@anthropic'],
    ['cd repo && git commit -m "Co-Authored-By: x"', 'Co-Authored-By'],
    ['echo hi | git commit -F - # Co-Authored-By: x', 'Co-Authored-By'],
  ])('blocks %j', (cmd, needle) => {
    const r = bashGuard(ev(cmd));
    expect(r.kind).toBe('block');
    expect((r as { reason: string }).reason).toContain('✗ Blocked: git commit contains AI attribution.');
    expect((r as { reason: string }).reason).toContain(needle);
  });

  it.each([
    'git commit -m "feat: clean (automated by AI)"',
    'git status',
    'echo "Co-Authored-By: x"',
    'git log --grep="Co-Authored-By"',
    'git commitish',
  ])('allows %j', (cmd) => {
    expect(bashGuard(ev(cmd))).toEqual({ kind: 'noop' });
  });

  it('ignores non-shell tools and missing command', () => {
    expect(bashGuard({ ...ev('git commit -m "Co-Authored-By: x"'), tool: undefined })).toEqual({ kind: 'noop' });
    expect(bashGuard(ev(undefined))).toEqual({ kind: 'noop' });
  });
});
